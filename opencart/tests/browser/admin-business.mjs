import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { resolve, join } from 'node:path';
import { readFile, mkdir } from 'node:fs/promises';
const base=new URL(process.env.CMTEH_BROWSER_BASE);
assert.ok(base.protocol==='http:' && ['127.0.0.1','localhost'].includes(base.hostname),'Local fixture only');
const require=createRequire(resolve(process.env.CMTEH_BROWSER_TOOLING,'package.json'));
const {chromium}=require('playwright');
const browser=await chromium.launch();
let stage="login";
try {
  const context=await browser.newContext({baseURL:base.href,acceptDownloads:true});
  const page=await context.newPage();
  await page.goto('/admin/');
  await page.locator('[name=username]').fill(process.env.CMTEH_ADMIN_USERNAME);
  await page.locator('[name=password]').fill((await readFile(process.env.CMTEH_ADMIN_PASSWORD_FILE,'utf8')).trim());
  await page.locator('#form-login button[type=submit]').click();
  await page.waitForURL(url=>url.searchParams.get('route')==='common/dashboard');
  await page.waitForLoadState('networkidle');
  if (await page.locator('#modal-security').isVisible()) await page.locator('#modal-security [data-bs-dismiss="modal"]').first().click();
  const token=new URL(page.url()).searchParams.get('user_token');
  const route=(view,extra={})=>'/admin/index.php?'+new URLSearchParams({route:'extension/cmteh/module/cmteh_leads',user_token:token,view,...extra});
  assert.equal(await page.locator('#nav-notification').count(),0,'Platform bell must not imply unread requests');
  assert.equal(await page.locator('#header a[aria-label="Обращения"]').count(),1);
  await mkdir(process.env.CMTEH_BROWSER_EVIDENCE,{recursive:true});
  stage='dashboard navigation';
  await Promise.all([page.waitForURL(url=>url.searchParams.get('route')==='extension/cmteh/module/cmteh_leads'),page.locator('#content').getByRole('link',{name:'Заявки',exact:true}).click()]);
  assert.equal(await page.locator('h1').innerText(),'Заявки и расценки');
  stage='contact HTML boundary';
  const probe='"><svg data-probe=cmteh onload=1>';
  await page.goto(route('contacts',{search:probe}));
  assert.equal(await page.locator('#business-search').inputValue(),probe);
  assert.equal(await page.locator('[data-probe=cmteh]').count(),0);
  assert.equal(await page.evaluate(()=>window.cmtehProbe),undefined);
  assert.ok((await page.locator('#business-table').innerText()).includes(probe));
  await Promise.all([page.waitForURL(url=>url.searchParams.get('page')==='2'),page.getByRole('link',{name:'Далее',exact:true}).click()]);
  await page.locator('#business-table tbody tr').first().waitFor();
  assert.equal(new URL(page.url()).searchParams.get('search'),probe);
  assert.equal(await page.locator('#business-table tbody tr').count(),1);
  assert.equal(await page.locator('[data-probe=cmteh]').count(),0);
  await page.goto(route('sources',{search:'Synthetic business acceptance'}));
  assert.ok((await page.locator('#business-table').innerText()).includes('https://example.test/'+probe));
  assert.equal(await page.locator('[data-probe=cmteh]').count(),0);
  stage='campaign HTML boundary';
  await page.goto('/admin/index.php?'+new URLSearchParams({route:'marketing/marketing.form',user_token:token,marketing_id:process.env.CMTEH_CAMPAIGN_ID}));
  assert.equal(await page.locator('#input-code').inputValue(),probe);
  assert.equal(new URL(await page.locator('#input-example1').inputValue()).searchParams.get('tracking'),probe);
  assert.equal(await page.locator('[data-probe=cmteh]').count(),0);
  assert.equal(await page.evaluate(()=>window.cmtehProbe),undefined);
  await page.goto('/admin/index.php?'+new URLSearchParams({route:'marketing/marketing',user_token:token,filter_code:probe}));
  assert.ok((await page.locator('#marketing').innerText()).includes(probe));
  assert.equal(await page.locator('[data-probe=cmteh]').count(),0);
  await Promise.all([page.waitForURL(url=>url.searchParams.get('route')==='marketing/marketing.form'),page.locator('#marketing tbody a').first().click()]);
  assert.equal(new URL(page.url()).searchParams.get('filter_code'),probe);
  assert.equal(await page.locator('#input-code').inputValue(),probe);
  for (const [width,height] of [[1440,1000],[390,844]]) {
    stage=`business journey ${width}`;
    await page.setViewportSize({width,height});
    await page.goto(route('contacts',{search:'Synthetic business acceptance'}));
    assert.equal(await page.locator('h1').innerText(),'Контакты обращений');
    assert.equal(await page.locator('#business-table tbody tr').count(),50);
    await Promise.all([page.waitForURL(url=>url.searchParams.get('page')==='2'),page.getByRole('link',{name:'Далее',exact:true}).click()]);
    await page.locator('#business-table tbody tr').first().waitFor();
    assert.equal(await page.locator('#business-table tbody tr').count(),2);
    await Promise.all([page.waitForURL(url=>url.searchParams.get('page')==='1'),page.getByRole('link',{name:'Назад',exact:true}).click()]);
    await page.locator('#business-table tbody tr').first().waitFor();
    await page.getByLabel('Тип',{exact:true}).selectOption('quote');
    await Promise.all([page.waitForURL(url=>url.searchParams.get('type')==='quote'),page.getByRole('button',{name:'Применить',exact:true}).click()]);
    await page.locator('#business-table tbody tr').first().waitFor();
    assert.equal(await page.locator('#business-table tbody tr').count(),1);
    assert.ok((await page.locator('#business-table').innerText()).includes('Оригинал файла в карточке'));
    await Promise.all([page.waitForURL(url=>url.searchParams.has('id')),page.locator('#business-table tbody a').first().click()]);
    const downloadLink=page.locator('a[href*="action=download"]');
    const downloadPromise=page.waitForEvent('download');await downloadLink.click();
    const download=await downloadPromise;
    assert.equal(await readFile(await download.path(),'utf8'),'001A;5');
    await page.goto(route('contacts',{search:'Synthetic business acceptance'}));
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Business page overflows viewport');
    await page.screenshot({path:join(process.env.CMTEH_BROWSER_EVIDENCE,`admin-business-${width}.png`)});
    await page.goto(route('reports',{search:'Synthetic business acceptance'}));
    assert.ok((await page.locator('#business-summary').innerText()).includes('52'));
    await page.getByLabel('С даты (UTC)',{exact:true}).fill('2099-01-01');
    await Promise.all([page.waitForURL(url=>url.searchParams.get('from')==='2099-01-01'),page.getByRole('button',{name:'Применить',exact:true}).click()]);
    await page.locator('#business-table tbody tr').first().waitFor();
    assert.ok((await page.locator('#business-table').innerText()).includes('Обращений по выбранным условиям нет'));
    await page.goto(route('sources',{search:'Synthetic business acceptance'}));
    assert.ok((await page.locator('#business-table').innerText()).includes('Источник не указан'));
    assert.equal(await page.locator('#business-table a').count(),0,'Declared URLs must stay text');
    await page.goto(route('capabilities'));
    await page.locator('summary').filter({hasText:'Покупатели и контакты'}).click();
    assert.ok(await page.getByText('Ответственные и стадии обращений',{exact:true}).isVisible());
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Capability page overflows viewport');
    await page.screenshot({path:join(process.env.CMTEH_BROWSER_EVIDENCE,`admin-capabilities-${width}.png`)});
  }
  stage='actual tracked campaign list and report';
  await page.goto('/admin/index.php?'+new URLSearchParams({route:'marketing/marketing.form',user_token:token,marketing_id:process.env.CMTEH_TRACKED_CAMPAIGN_ID}));
  const trackingUrl=await page.locator('#input-example1').inputValue();
  const visitor=await browser.newContext({baseURL:base.href});
  assert.equal((await visitor.request.get(trackingUrl)).status(),200);
  assert.equal((await visitor.request.get(base.href)).status(),200);
  await visitor.close();
  await page.goto('/admin/index.php?'+new URLSearchParams({route:'marketing/marketing',user_token:token,filter_code:process.env.CMTEH_TRACKING_CODE}));
  assert.equal(await page.locator('h1').innerText(),'Рекламные кампании');
  assert.ok((await page.locator('#content').innerText()).includes('включая повторы и ошибки 404'));
  assert.equal(await page.getByRole('columnheader',{name:'Заказы',exact:true}).count(),0);
  const campaignRow=page.locator('#marketing tbody tr').filter({hasText:'Synthetic tracked campaign'});
  assert.equal(await campaignRow.locator('td').nth(3).innerText(),'2');
  await page.screenshot({path:join(process.env.CMTEH_BROWSER_EVIDENCE,'admin-marketing-390.png')});
  await Promise.all([page.waitForURL(url=>url.searchParams.get('route')==='marketing/marketing.form'),campaignRow.locator('a').click()]);
  await page.locator('#form-marketing a[href="#tab-report"]').click();
  assert.ok(await page.locator('#tab-report').isVisible());
  assert.equal(await page.locator('#report tbody tr').count(),2);
  assert.equal(await page.locator('#report').getByRole('cell',{name:'СМ ТЕХНО',exact:true}).count(),2);
  assert.ok(!(await page.locator('#report').innerText()).includes('Your Store'));
  assert.equal(await page.locator('#report a[href*="customer/customer"], #report a[href*="geoiptool"]').count(),0);
  await page.screenshot({path:join(process.env.CMTEH_BROWSER_EVIDENCE,'admin-marketing-report-390.png')});
  console.log('PASS business browser 1440/390: contact pagination, type/date filter, private original, reports, unknown source, capability disclosure and truthful marketing');
}catch(error){
  throw new Error(stage+': '+String(error?.message||error).replace(/user_token=[^&\s"'<>]+/g,'user_token=[REDACTED]'));
}finally{await browser.close();}
